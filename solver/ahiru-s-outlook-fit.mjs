import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createCpuReplay } from '../game/js/cpuOpponent.js?v=20261122-0070';
import { ScoreManager } from '../game/js/scoreManager.js?v=20261122-0070';
import { snapshotCards } from '../game/js/battleReplay.js?v=20261122-0070';
import { applySModel, sOutlookFeatures } from '../game/js/ahiruSOutlook.js?v=20261122-0070';
