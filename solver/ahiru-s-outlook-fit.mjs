const [journal, output, masterOptions = '{}'] = process.argv.slice(2);
assert.ok(journal && output, 'PRO補正作成のgames.ndjsonと出力先が必要です');
const fetchWithNetwork = globalThis.fetch;
globalThis.fetch = async url => new URL(url).protocol === 'file:' ? new Response(await readFile(fileURLToPath(new URL(url))))
    : fetchWithNetwork(url);
globalThis.window = { BUILD_VERSION: 'v20261122-0070' };
const grades = new Set(['S', 'S+', 'SS', 'SS+', 'SSS']);

function addScene(samples, observation, phase, seen) {
    const key = observation.turn + ':' + phase;
    if (seen.has(key)) return;
    seen.add(key);
    const data = sOutlookFeatures(observation, phase);
    if (data?.remaining > 0) samples.push(data.features);
}

async function readFresh() {
    const games = [];
    for (let index = 0; index < 500; index++) {
        const record = await createCpuReplay({ difficulty: 'fresh', seed: 'ahiru/outlook/0070/fresh/' + index, captureViewing: true });
        const samples = [], seen = new Set();
        for (const turn of record.turns) {
            for (const [phase, snapshot] of [['training', turn.choices[0]?.before], ['action', turn.actionStart], ['meeting', turn.meetingStart]]) {
                if (!snapshot) continue;
                addScene(samples, { difficulty: 'fresh', stats: snapshot.player, turn: turn.turn,
                    tokens: snapshot.tokens, owned: snapshotCards(snapshot).map(id => record.instances[id]).filter(card => !card.autoGenerated),
                    rankTable: record.definitions.ranks }, phase, seen);
            }
        }
        games.push({ samples, reached: Number(grades.has(record.result.score.rank.grade)) });
    }
    return games;
}

async function readPro() {
    const s = new ScoreManager(null, { migrateHighScore: false });
    await s.loadRankData(new URL('../game/data/rankPro.csv', import.meta.url).href);
    const target = s.rankTable.find(row => row.grade === 'S').rankThreshold;
    const cards = await readFile(new URL('../game/data/cards_pro.csv', import.meta.url));
    const cardVersion = 'sha256:' + createHash('sha256').update(cards).digest('hex');
    const rows = (await readFile(journal, 'utf8')).trim().split('\n').map(JSON.parse).sort((a, b) => a.index - b.index);
    assert.ok(rows.length >= 250 && new Set(rows.map(row => row.index)).size === rows.length);
    return rows.map(row => {
        assert.equal(row.cardVersion, cardVersion);
        assert.equal(row.rankVersion, s.dataVersion);
        const actual = s.calculateScore({ difficulty: 'pro', player: row.stats });
        assert.equal(actual.displayScore, row.score);
        const samples = [], seen = new Set();
        for (const { phase, observation, action } of row.decisions) {
            const scene = { ...observation, rankTable: s.rankTable };
            if (phase === 'deletion') addScene(samples, scene, 'meeting', seen);
            else if (!observation.allowSkip) {
                addScene(samples, scene, 'training', seen);
                const owned = [...scene.owned, ...action.indices.map(index => scene.candidates[index])];
                addScene(samples, { ...scene, owned }, 'action', seen);
            }
        }
        return { samples, reached: Number(row.score >= target) };
    });
}

async function readMaster() {
    const rules = await loadMasterRules();
    const decide = createMasterPolicy({ ...rules, ...JSON.parse(masterOptions) });
    const games = [];
    for (let index = 0; index < 1500; index++) {
        const samples = [], seen = new Set();
        const final = playMaster('ahiru/outlook/0070/master/' + index, rules, decide, null, observation => {
            const phase = observation.kind === 'delete' ? 'meeting' : observation.kind === 'place' ? 'action'
                : observation.kind === 'outing' || observation.offer?.id || observation.kind === 'staff' ? 'outing' : 'training';
            addScene(samples, { ...observation, difficulty: 'int', rankTable: rules.scorer.rankTable }, phase, seen);
        });
        games.push({ samples, reached: Number(grades.has(final.score.rank.grade)) });
    }
    return games;
}

function fit(games) {
    const rows = games.flatMap(game => game.samples.map(features => ({ features, reached: game.reached })));
    const size = rows[0].features.length, count = rows.length;
    const centers = rows[0].features.map((_, i) => rows.reduce((sum, row) => sum + row.features[i], 0) / count);
    const scales = centers.map((mean, i) => Math.max(0.01,
        Math.sqrt(rows.reduce((sum, row) => sum + (row.features[i] - mean) ** 2, 0) / count)));
    const samples = rows.map(({ features, reached }) => ({ values: features.map((x, i) => (x - centers[i]) / scales[i]), reached }));
    const weights = Array(size).fill(0);
    let bias = 0;
    for (let iteration = 0; iteration < 225; iteration++) {
        let biasGradient = 0;
        const gradient = Array(size).fill(0);
        for (const { values, reached } of samples) {
            let margin = bias;
            for (let i = 0; i < size; i++) margin += values[i] * weights[i];
            const error = 1 / (1 + Math.exp(-margin)) - reached;
            biasGradient += error;
            for (let i = 0; i < size; i++) gradient[i] += values[i] * error;
        }
        bias -= 0.25 * biasGradient / count;
        for (let i = 0; i < size; i++) weights[i] -= 0.25 * (gradient[i] / count + 0.012 * weights[i]);
    }
    return { centers, scales, weights, bias, games: games.length };
}

function check(games) {
    const bins = { red: [0, 0], yellow: [0, 0], green: [0, 0] };
    let squaredError = 0, count = 0;
    for (let fold = 0; fold < 5; fold++) {
        const model = fit(games.filter((_, i) => i % 5 !== fold));
        for (const { samples, reached } of games.filter((_, i) => i % 5 === fold)) {
            for (const features of samples) {
                const p = applySModel(features, model);
                const bin = bins[p >= 0.85 ? 'green' : p <= 0.4 ? 'red' : 'yellow'];
                bin[0]++;
                bin[1] += reached;
                squaredError += (p - reached) ** 2;
                count++;
            }
        }
    }
    return { games: games.length, scenes: count, brier: squaredError / count,
        bins: Object.fromEntries(Object.entries(bins).map(([name, [scenes, reached]]) =>
            [name, { scenes, reached, rate: scenes ? reached / scenes : null }])) };
}

const models = {}, validation = {};
for (const [difficulty, load] of [['fresh', readFresh], ['pro', readPro], ['int', readMaster]]) {
    const games = await load();
    assert.ok(games.every(game => game.samples.length));
    models[difficulty] = fit(games);
    validation[difficulty] = check(games);
    console.log(difficulty, JSON.stringify(validation[difficulty]));
}
await writeFile(output, 'export const S_MODELS = ' + JSON.stringify(models, null, 4) + ';\n');
await writeFile(output + '.validation.json', JSON.stringify(validation, null, 2) + '\n');
