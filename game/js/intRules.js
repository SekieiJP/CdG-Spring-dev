const isSpringTurn = state => !!state.config.turns[state.turn]?.spring;
const intState = state => {
    state.ruleState.int ||= { outing: null, springDiscard: [] };
    state.ruleState.int.springDiscard ||= [];
    return state.ruleState.int;
};

function getTrainingOfferConfig(state, mode = 'normal') {
    if (mode === 'inspiration') return { rarity: 'SR', offerCount: 3, pickCount: 1, allowSkip: true };
    const turn = state.config.turns[state.turn];
    if (!turn?.training || turn.type === 'outing') return null;
    return { rarity: turn.training, offerCount: turn.offerCount, pickCount: turn.pickCount, allowSkip: false };
}

function isOutingTurn(state) {
    return state.config.turns[state.turn]?.type === 'outing';
}

function createRuleState() {
    return { int: { outing: null, springDiscard: [] } };
}

function prepareActionPhase(state, turnManager) {
    const spring = isSpringTurn(state);
    const passion = state.tokens?.passion || 0;
    const fatigue = state.tokens?.fatigue || 0;
    const baseCount = spring ? 3 : 4;
    const drawCount = Math.max(0, baseCount + passion - fatigue);
    state.tokens.passion = 0;
    state.tokens.fatigue = 0;
    state.lastDrawNotification = passion || fatigue ? { passion, fatigue, drawCount } : null;
    state.shuffleDeck();
    if (!spring || state.player.deck.length >= drawCount) state.drawCards(drawCount);
    turnManager.logger?.log(`${spring ? '講習' : '通常'}ドロー: ${drawCount}枚を要求しました`, 'action');
    return true;
}

function beforeAction(state, cardManager) {
    if (!isSpringTurn(state)) return;
    const basicCourseCard = cardManager.allCards.find(card => card.cardName === '質問対応の基本');
    if (!basicCourseCard) return;
    for (const slotId of ['leader', 'teacher']) {
        const slot = state.slots.find(slot => slot.id === slotId);
        if (!slot) continue;
        const placed = state.player.placed[slotId] || [];
        const empty = Math.max(0, slot.capacity - placed.length);
        for (let index = 0; index < empty; index++) {
            const autoCard = { ...basicCourseCard, autoGenerated: true,
                instanceId: `${state.runId}:auto:${state.turn}:${slotId}:${index}` };
            placed.push(autoCard);
        }
    }
}

function getActionValidationError(state) {
    if (!isSpringTurn(state)) return null;
    const leader = state.player.placed.leader || [];
    const teacher = state.player.placed.teacher || [];
    const leaderCapacity = state.slots.find(slot => slot.id === 'leader')?.capacity || 0;
    const teacherCapacity = state.slots.find(slot => slot.id === 'teacher')?.capacity || 0;
    if (leader.length < leaderCapacity || teacher.length < teacherCapacity) return null;
    const hasCourse = Object.values(state.player.placed).flat().some(card => card?.category === '教務');
    return hasCourse ? null : '講習では教務カードを1枚以上配置してください';
}

function finishAction(state) {
    if (!isSpringTurn(state)) return;
    const int = intState(state);
    for (const slot of state.slots) {
        const placed = state.player.placed[slot.id] || [];
        for (const card of placed) {
            if (!card.autoGenerated) int.springDiscard.push(card);
        }
        state.player.placed[slot.id] = [];
    }
}

function skipReturnAllToDeck(state) {
    return isSpringTurn(state);
}

function startMeetingPhase(state) {
    return isSpringTurn(state);
}

function getDeleteCandidates(state, context = 'meeting') {
    if (context === 'outing') {
        return [...state.player.deck, ...state.player.hand, ...Object.values(state.player.placed).flat(),
            ...Object.values(state.player.zones || {}).flat(), ...(state.ruleState.int?.springDiscard || [])]
            .filter(card => !card?.autoGenerated);
    }
    if (isSpringTurn(state)) {
        return [...state.player.deck, ...state.player.hand, ...(state.ruleState.int?.springDiscard || [])];
    }
    return [...state.player.deck];
}

function returnSpringCardsToDeck(state) {
    const int = intState(state);
    state.player.deck.push(...state.player.hand, ...int.springDiscard);
    state.player.hand = [];
    int.springDiscard = [];
}

